import itertools
import numpy as np
import cv2
import matplotlib.pyplot as plt


def apply_affine(M, pts):
    pts = np.asarray(pts, dtype=np.float32)
    if pts.ndim == 1:
        pts = pts[None, :]
    ones = np.ones((len(pts), 1), dtype=np.float32)
    pts_h = np.hstack([pts, ones])
    return pts_h @ M.T


# Old SLM-side ThorCam triangle, in the printed order
tri_slm_cam = np.array(
    [
        [779.2820323, 580.0],
        [640.7179677, 580.0],
        [710.0,       460.0],
    ],
    dtype=np.float32,
)

# Use the Fourier-calibration zero order / b point from your printout
zero_slm_cam = np.array([705.05789009, 519.93369574], dtype=np.float32)

# Load DMD triangle calibration
cal = np.load("dmdsuite/calibration/triangle_affine_onpass.npz", allow_pickle=True)

tri_dmd_cam_raw = np.asarray(cal["tri_cam_pts"], dtype=np.float32)
zero_dmd_cam = np.asarray(cal["zero_cam_xy"], dtype=np.float32).reshape(2)

best = None
results = []

for perm in itertools.permutations(range(3)):
    # Reorder DMD-side triangle to correspond to old SLM-side triangle order
    tri_dmd_cam = tri_dmd_cam_raw[list(perm)]

    # Fit ThorCam_SLM triangle -> ThorCam_DMD triangle
    M_slmcam_to_dmdcam = cv2.getAffineTransform(
        tri_slm_cam.astype(np.float32),
        tri_dmd_cam.astype(np.float32),
    )

    # Predict where old zero order should land on DMD ThorCam
    pred_zero_dmd_cam = apply_affine(M_slmcam_to_dmdcam, zero_slm_cam)[0]

    zero_err = np.linalg.norm(pred_zero_dmd_cam - zero_dmd_cam)

    results.append((perm, zero_err, pred_zero_dmd_cam, M_slmcam_to_dmdcam))

    if best is None or zero_err < best[1]:
        best = results[-1]

print("\nPermutation test:")
for perm, err, pred_zero, _ in results:
    print(f"perm={perm}, zero-order error = {err:.2f} px, pred_zero={pred_zero}")

best_perm, best_err, best_pred_zero, best_M = best

print("\nBEST:")
print("DMD_TRIANGLE_ORDER =", list(best_perm))
print("zero-order error [px] =", best_err)
print("predicted zero on DMD ThorCam =", best_pred_zero)
print("actual zero on DMD ThorCam    =", zero_dmd_cam)


