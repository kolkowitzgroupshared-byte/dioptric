"""
Generate Nuvu -> ThorCam_DMD -> DMD calibration using the shared SLM triangle.

Use case
--------
You generated an SLM triangle using the SLM/Fourier ThorCam coordinate system,
then observed the same three spots with the DMD-side ThorCam during DMD calibration.
This script uses that triangle as the bridge between the Nuvu coordinate system
and the DMD-side ThorCam/DMD coordinate systems.

Outputs
-------
1. slmsuite/calibration/nuvu_to_thorcam_slm.npz
2. dmdsuite/calibration/nuvu_to_thorcam_dmd.npz
3. dmdsuite/calibration/nv_chain_nuvu_thorcamDMD_dmd_1277.npz

Important
---------
Point ordering matters. The 3 DMD-side triangle points loaded from
triangle_affine_onpass.npz must correspond to OLD_TRIANGLE_THORCAM_SLM in the
same order. If not, change DMD_TRIANGLE_ORDER below.
"""

