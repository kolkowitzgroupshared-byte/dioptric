# These were in your nuvu2thorcam_calibration() function.
SLM_CAL_COORDS_THORCAM = np.array(
    [
        [883.205, 640.000],
        [536.795, 640.000],
        [710.000, 340.000],
    ],
    dtype=np.float32,
)

SLM_CAL_COORDS_NUVU = np.array(
    [
        [338.040, 361.354],
        [311.711,  11.032],
        [ 18.043, 209.580],
    ],
    dtype=np.float32,
)

# The SLM triangle generated by calibration_triangle(), in ThorCam_SLM coordinates.
# User log:
# thorcam coords: [[779.2820323 640.7179677 710.       ]
#                  [580.        580.        460.       ]]
# Converted here to Nx2: [[x0, y0], [x1, y1], [x2, y2]].
OLD_TRIANGLE_THORCAM_SLM = np.array(
    [
        [779.2820323, 580.0],
        [640.7179677, 580.0],
        [710.0000000, 460.0],
    ],
    dtype=np.float32,
)

# Reorder the DMD-side triangle points to match OLD_TRIANGLE_THORCAM_SLM.
# The DMD calibration detected points may be sorted by brightness, not by geometry.
# Start with [0, 1, 2]. If the diagnostic plot looks mismatched, change this.
# Example: [2, 0, 1] means:
#   old point 0 corresponds to tri_cam_pts[2]
#   old point 1 corresponds to tri_cam_pts[0]
#   old point 2 corresponds to tri_cam_pts[1]
# DMD_TRIANGLE_ORDER = [0, 1, 2]
DMD_TRIANGLE_ORDER = [2, 1, 0]

# =============================================================================
# Path helpers
